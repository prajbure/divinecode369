"""Export the canonical mobile OpenAPI subset and deterministic Kotlin DTOs."""
import json
import re
from pathlib import Path
from app.main import app

ROOT=Path(__file__).resolve().parents[1]
contract=app.openapi()
paths={k:v for k,v in contract['paths'].items() if k.startswith(('/api/v1/mobile/','/auth/mobile/'))}
schemas=contract['components']['schemas'];needed=set()
def refs(value):
    if isinstance(value,dict):
        if '$ref' in value:
            name=value['$ref'].split('/')[-1]
            if name not in needed:needed.add(name);refs(schemas[name])
        for v in value.values():refs(v)
    elif isinstance(value,list):
        for v in value:refs(v)
refs(paths)
output={**contract,'paths':paths,'components':{'schemas':{k:schemas[k] for k in sorted(needed)},'securitySchemes':contract['components'].get('securitySchemes',{})}}
folder=ROOT/'contracts';folder.mkdir(exist_ok=True)
(folder/'mobile-v1.openapi.json').write_text(json.dumps(output,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
def kind(s):
    if '$ref' in s:return s['$ref'].split('/')[-1]
    if 'anyOf' in s:
        parts=[p for p in s['anyOf'] if p.get('type')!='null']
        result=kind(parts[0]) if len(parts)==1 else 'JsonElement'
        return result+'?' if any(p.get('type')=='null' for p in s['anyOf']) else result
    t=s.get('type')
    if t=='array':return 'List<'+kind(s.get('items',{}))+'>'
    if t=='object':return 'Map<String, '+kind(s['additionalProperties'])+'>' if isinstance(s.get('additionalProperties'),dict) else 'JsonObject'
    return {'string':'String','integer':'Int','number':'Double','boolean':'Boolean'}.get(t,'JsonElement')
lines=['// Generated by scripts/mobile_contract.py. Do not edit manually.','package `in`.divinecode369.app.data.api','', 'import kotlinx.serialization.Serializable','import kotlinx.serialization.json.JsonElement','import kotlinx.serialization.json.JsonObject','']
for name in sorted(needed):
    s=schemas[name]
    if s.get('type')!='object' or not s.get('properties'):continue
    lines+=['@Serializable','data class '+name+'(']
    fields=[]
    for key,p in s['properties'].items():
        t=kind(p);default=''
        if key not in s.get('required',[]):
            d=p.get('default')
            if t.endswith('?'):default=' = null'
            elif t.startswith('List<'):default=' = emptyList()'
            elif t.startswith('Map<'):default=' = emptyMap()'
            elif t=='JsonObject':default=' = JsonObject(emptyMap())'
            elif t=='String':default=' = '+json.dumps(d or '',ensure_ascii=False)
            elif t=='Boolean':default=' = '+str(bool(d)).lower()
            elif t in ('Int','Double'):default=' = '+str(d or 0)+('.0' if t=='Double' and isinstance(d or 0,int) else '')
            else:default=' = '+t+'()'
        fields.append('    val `'+key+'`: '+t+default)
    lines+=[',\n'.join(fields),')','']
target=ROOT/'android/app/src/main/java/in/divinecode369/app/data/api/MobileModels.kt';target.parent.mkdir(parents=True,exist_ok=True);target.write_text('\n'.join(lines),encoding='utf-8')
print('Exported',len(paths),'routes and',len(needed),'schemas.')
